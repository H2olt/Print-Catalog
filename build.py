"""
Orynt3D Catalog Builder (stage 2 of 2 — runs on Netlify, or locally to preview)

Turns the committed data snapshot + site design into the publishable site:

    data/catalog.json + data/thumbs/   (from export.py)
    site/index.html                    (the viewer design)
    theme.json                         (optional colour/font/layout overrides)
        ↓
    dist/  — index.html, data.js, thumbs/

Standard library only. Never touches the Orynt3D database, so it runs anywhere.
"""

import json
import shutil
import sys
from pathlib import Path

ROOT      = Path(__file__).parent
DATA_DIR  = ROOT / "data"
SITE_DIR  = ROOT / "site"
THEME     = ROOT / "theme.json"
DIST      = ROOT / "dist"

COLOR_MAP = {
    "background":       "--bg-deepest",
    "background_card":  "--bg-card",
    "background_panel": "--bg-panel",
    "border":           "--border",
    "border_light":     "--border-light",
    "accent":           "--amber",
    "accent_bright":    "--amber-bright",
    "accent_dim":       "--amber-dim",
    "text_primary":     "--text-primary",
    "text_secondary":   "--text-secondary",
    "text_muted":       "--text-muted",
    "tag_background":   "--tag-bg",
    "tag_border":       "--tag-border",
}
LAYOUT_MAP = {
    "card_min_width_px": "--card-min-w",
    "grid_gap_px":       "--grid-gap",
    "sidebar_width_px":  "--sidebar-w",
    "thumb_radius_px":   "--thumb-radius",
}


def fail(msg):
    print(f"ERROR: {msg}")
    sys.exit(1)


def theme_overrides(theme):
    lines = []
    for key, var in COLOR_MAP.items():
        if key in theme.get("colors", {}):
            lines.append(f"  {var}: {theme['colors'][key]};")
    for key, var in LAYOUT_MAP.items():
        if key in theme.get("layout", {}):
            lines.append(f"  {var}: {theme['layout'][key]}px;")
    fonts = theme.get("fonts", {})
    if "display_font" in fonts:
        lines.append(f"  --font-display: '{fonts['display_font']}', serif;")
    if "body_font" in fonts:
        lines.append(f"  --font-body: '{fonts['body_font']}', sans-serif;")
    if "mono_font" in fonts:
        lines.append(f"  --font-mono: '{fonts['mono_font']}', monospace;")
    if not lines:
        return ""
    # The original builder emitted a bare @import outside <style>, which
    # browsers render as visible text. A <link> tag is the valid form.
    imp = fonts.get("_font_import", "")
    link = f'<link rel="stylesheet" href="{imp}">\n' if imp else ""
    return f"{link}<style>\n:root {{\n" + "\n".join(lines) + "\n}\n</style>"


def main():
    catalog_file = DATA_DIR / "catalog.json"
    html_file    = SITE_DIR / "index.html"
    if not catalog_file.exists():
        fail(f"{catalog_file} not found. Run export.py on the PC with Orynt3D first.")
    if not html_file.exists():
        fail(f"{html_file} not found.")

    catalog = json.loads(catalog_file.read_text(encoding="utf-8"))
    meta, models = catalog["meta"], catalog["models"]
    if meta.get("entry_limited"):
        print("WARN: this data came from a test export (entry_limit was set).")
    if meta.get("test_images"):
        print("WARN: test-image export — every thumbnail is a SAMPLE / MISSING stand-in.")

    if DIST.exists():
        shutil.rmtree(DIST)
    DIST.mkdir()

    # data.js — same globals the viewer has always read
    with open(DIST / "data.js", "w", encoding="utf-8") as f:
        f.write("// Auto-generated by build.py — do not edit manually\n\n")
        f.write("const CATALOG_META = ")
        json.dump(meta, f, ensure_ascii=False, indent=2)
        f.write(";\n\nconst CATALOG_MODELS = ")
        json.dump(models, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")

    html = html_file.read_text(encoding="utf-8")
    if THEME.exists():
        overrides = theme_overrides(json.loads(THEME.read_text(encoding="utf-8")))
        if overrides:
            html = html.replace("</head>", f"{overrides}\n</head>", 1)
    (DIST / "index.html").write_text(html, encoding="utf-8")

    # Any other design assets placed in site/ (css, js, images) ship as-is
    for item in SITE_DIR.iterdir():
        if item.name == "index.html":
            continue
        dest = DIST / item.name
        shutil.copytree(item, dest) if item.is_dir() else shutil.copy2(item, dest)

    thumbs = DATA_DIR / "thumbs"
    if thumbs.exists():
        shutil.copytree(thumbs, DIST / "thumbs")

    print(f"✓ Built {len(models)} models → {DIST}")


if __name__ == "__main__":
    main()
